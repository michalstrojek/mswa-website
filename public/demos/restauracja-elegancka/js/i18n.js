window.NOVA_getLang = function () {
  return localStorage.getItem("nova-lang") === "en" ? "en" : "pl";
};

window.NOVA_setLang = function (lang) {
  const next = lang === "en" ? "en" : "pl";
  localStorage.setItem("nova-lang", next);
  window.NOVA_applyLang(next);
};

window.NOVA_applyLang = function (lang) {
  const dict = window.NOVA_I18N[lang] || window.NOVA_I18N.pl;
  document.documentElement.lang = lang;

  document.querySelectorAll("[data-i18n]").forEach((el) => {
    const key = el.getAttribute("data-i18n");
    if (!key || dict[key] == null) return;
    el.textContent = dict[key];
  });

  document.querySelectorAll("[data-i18n-html]").forEach((el) => {
    const key = el.getAttribute("data-i18n-html");
    if (!key || dict[key] == null) return;
    el.innerHTML = dict[key];
  });

  document.querySelectorAll("[data-i18n-placeholder]").forEach((el) => {
    const key = el.getAttribute("data-i18n-placeholder");
    if (!key || dict[key] == null) return;
    el.setAttribute("placeholder", dict[key]);
  });

  document.querySelectorAll("[data-i18n-aria]").forEach((el) => {
    const key = el.getAttribute("data-i18n-aria");
    if (!key || dict[key] == null) return;
    el.setAttribute("aria-label", dict[key]);
  });

  const titleEl = document.querySelector("title[data-i18n]");
  if (titleEl) {
    const key = titleEl.getAttribute("data-i18n");
    if (dict[key]) document.title = dict[key];
  } else if (dict["meta.title"] && document.body.dataset.page === "home") {
    document.title = dict["meta.title"];
  }

  document.querySelectorAll("[data-lang]").forEach((btn) => {
    const active = btn.getAttribute("data-lang") === lang;
    btn.classList.toggle("is-lang-active", active);
    if (active) btn.setAttribute("aria-current", "true");
    else btn.removeAttribute("aria-current");
  });

  document.dispatchEvent(new CustomEvent("nova:lang", { detail: { lang } }));
};
